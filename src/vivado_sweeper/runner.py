METRIC_ORDER = ['wns', 'tns', 'whs', 'ths', 'timing_met', 'tns_failing', 'ths_failing', 'wpws',
                'lut', 'lut_pct', 'lutram', 'lutram_pct', 'ff', 'ff_pct', 'bram', 'bram_pct',
                'uram', 'uram_pct', 'dsp', 'dsp_pct', 'io', 'io_pct',
                'power_total_w', 'power_dynamic_w', 'power_static_w', 'junction_temp_c', 'power_confidence']
TAIL = ['synth_s', 'impl_s']


def load_records(out_dir):
    out = []
    for d in sorted(Path(out_dir).iterdir()) if Path(out_dir).is_dir() else []:
        f = d / 'done.json'
        if f.is_file():
            try:
                with open(f, encoding='utf-8') as fh:
                    out.append(json.load(fh))
            except (OSError, ValueError):
                pass
    return sorted(out, key=lambda r: r.get('index', 0))


def write_results(out_dir):
    """Rewrite results.csv from every done.json (columns can grow as hooks add metrics)."""
    import csv
    records = load_records(out_dir)
    if not records:
        return None
    swept = []
    for r in records:
        swept += [k for k in r.get('settings', {}) if k not in swept]
    metrics = [k for k in METRIC_ORDER if any(k in r.get('metrics', {}) for r in records)]
    for r in records:
        metrics += [k for k in r.get('metrics', {}) if k not in metrics and k not in TAIL]
    tail = [k for k in TAIL if any(k in r.get('metrics', {}) for r in records)]
    head = ['index', 'name', 'parent', 'status']
    taken = set(head + metrics + tail + ['changes', 'problems', 'seconds', 'run_dir'])
    cols = [(k if k not in taken else 'define.' + k, k) for k in swept]
    header = head + [c for c, _ in cols] + metrics + tail + ['seconds', 'changes', 'problems', 'run_dir']
    path = Path(out_dir) / 'results.csv'
    tmp = path.with_suffix('.csv.tmp')
    with open(tmp, 'w', newline='', encoding='utf-8') as f:
        w = csv.writer(f)
        w.writerow(header)
        for r in records:
            m = r.get('metrics', {})
            w.writerow([r.get('index'), r.get('name'), r.get('parent'), r.get('status')]
                       + [r.get('state', {}).get(k, '') for _, k in cols]
                       + [m.get(k, '') for k in metrics + tail]
                       + [r.get('seconds', ''), '; '.join(r.get('changes', [])), ' | '.join(r.get('problems', [])),
                          str(Path(out_dir) / r.get('dirname', ''))])
    os.replace(tmp, path)
    (Path(out_dir) / 'summary.txt').write_text(summary_table(records) + '\n', encoding='utf-8')
    return path


def summary_table(records):
    cols = [('run', lambda r: r.get('dirname', r.get('name'))), ('status', lambda r: r.get('status', '')),
            ('WNS', lambda r: r['metrics'].get('wns', '')), ('LUT', lambda r: r['metrics'].get('lut', '')),
            ('FF', lambda r: r['metrics'].get('ff', '')), ('BRAM', lambda r: r['metrics'].get('bram', '')),
            ('DSP', lambda r: r['metrics'].get('dsp', '')), ('P(W)', lambda r: r['metrics'].get('power_total_w', '')),
            ('time', lambda r: duration(r.get('seconds', 0)))]
    rows = [[h for h, _ in cols]] + [[str(get(dict(r, metrics=r.get('metrics', {})))) for _, get in cols]
                                    for r in records]
    widths = [max(len(row[i]) for row in rows) for i in range(len(cols))]
    return '\n'.join('  '.join(c.ljust(w) for c, w in zip(row, widths)).rstrip() for row in rows)


def reparse(cfg, out_dir, say=print):
    """Recompute every run's metrics and checks from the files in its directory."""
    out_dir = Path(out_dir)
    n = 0
    for d in sorted(out_dir.iterdir()):
        done = d / 'done.json'
        if not done.is_file():
            continue
        with open(done, encoding='utf-8') as f:
            r = json.load(f)
        metrics = reports.collect(str(d), cfg.hierarchical if cfg else [])
        metrics.update(hooks.merge_metrics(str(d), {}))
        metrics.update({k: v for k, v in r.get('metrics', {}).items() if k in TAIL})
        r['metrics'] = metrics
        if r.get('status') in (OK, 'verify_failed'):
            vds = reports.find_vds(d)
            state = {k: (True if v == 'on' else False if v == 'off' else v) for k, v in r.get('state', {}).items()}
            problems = (verify.check_build(reports.read_text(vds), state, cfg.verify if cfg else {})
                        if vds else ['no synthesis log (.vds) in the run directory'])
            r['status'] = 'verify_failed' if problems else OK
            r['problems'] = problems
        with open(done, 'w', encoding='utf-8') as f:
            json.dump(r, f, indent=1)
        say('%s  %s  %s' % (d.name, r['status'], headline(metrics)))
        n += 1
    path = write_results(out_dir)
    return n, path
