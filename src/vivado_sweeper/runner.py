"""Running a sweep: one Vivado build per planned run, everything kept in <output>/<timestamp>/.

    <output>/<timestamp>_<sweep>/
        sweep.vsw  plan.txt  vsweep.toml  originals/      what was asked for, and the files before
        results.csv  summary.txt                          one row per finished run (rewritten each time)
        01_baseline/
            settings.json  vh/<file>.vh                   exactly what this run built with
            build.tcl  build.log  vivado.log              the Vivado session
            *.vds  synth_runme.log  impl_runme.log        copied from the runs
            timing_summary.rpt  utilization.rpt  power.rpt  [*.bit *.ltx]
            metrics.json  pre_build.log  post_build.log   from hooks, if any
            done.json                                     status, metrics, problems, times
"""
import datetime
import glob
import json
import os
import queue
import shutil
import signal
import threading
import time
import traceback
from importlib import resources
from pathlib import Path

from . import __version__, hooks, reports, verify, workspace
from .guard import Guard
from .vh import fmt
from .vivado import Procs, Vivado, on_windows_drive

OK = 'ok'


class Interrupted(Exception):
    pass


def tcl_brace(s):
    s = str(s)
    if any(c in s for c in '{}\\'):
        raise ValueError('cannot pass %r to Tcl (braces or backslashes)' % s)
    return '{' + s + '}'


def build_tcl(cfg, ws, run_dir, vivado, jobs):
    header = [
        '# generated by vsweep %s' % __version__,
        'set vs(xpr) %s' % tcl_brace(vivado.path(ws.xpr)),
        'set vs(out) %s' % tcl_brace(vivado.path(run_dir)),
        'set vs(synth_run) %s' % tcl_brace(cfg.synth_run),
        'set vs(impl_run) %s' % tcl_brace(cfg.impl_run),
        'set vs(stop_after) %s' % cfg.stop_after,
        'set vs(jobs) %d' % jobs,
        'set vs(hier) [list %s]' % ' '.join(tcl_brace(h) for h in cfg.hierarchical),
        'set vs(keep) [list %s]' % ' '.join(cfg.keep),
        'set vs(extra_tcl) %s' % tcl_brace(vivado.path(cfg.extra_tcl) if cfg.extra_tcl else ''),
        '',
    ]
    body = resources.files('vivado_sweeper').joinpath('tcl/build.tcl').read_text(encoding='utf-8')
    return '\n'.join(header) + body


def duration(seconds):
    seconds = int(seconds)
    h, m, s = seconds // 3600, seconds // 60 % 60, seconds % 60
    return '%dh%02dm' % (h, m) if h else '%dm%02ds' % (m, s) if m else '%ds' % s


def headline(metrics):
    """The few numbers worth a line on the console."""
    parts = []
    if metrics.get('wns') not in (None, ''):
        parts.append('WNS %s' % metrics['wns'])
    for key, label in (('lut', 'LUT'), ('ff', 'FF'), ('bram', 'BRAM'), ('uram', 'URAM'), ('dsp', 'DSP')):
        if metrics.get(key) not in (None, ''):
            pct = metrics.get(key + '_pct')
            parts.append('%s %s%s' % (label, metrics[key], ' (%s%%)' % pct if pct and key == 'lut' else ''))
    if metrics.get('power_total_w') not in (None, ''):
        parts.append('P %s W' % metrics['power_total_w'])
    return '  '.join(parts)


class Runner:
    def __init__(self, cfg, planned, out_dir, sweep_text='', plan_text='', parallel=1, resume=False,
                 stop_on_fail=False, keep_workspaces=False, total=None, say=None):
        self.cfg = cfg
        self.planned = planned                       # the runs to execute, in order
        self.total = total or len(planned)           # how many runs the whole sweep has
        self.out_dir = Path(out_dir)
        self.sweep_text, self.plan_text = sweep_text, plan_text
        self.parallel = max(1, int(parallel))
        self.resume, self.stop_on_fail, self.keep_workspaces = resume, stop_on_fail, keep_workspaces
        self.procs = Procs()
        self.stopping = threading.Event()
        self.interrupted = False
        self.print_lock = threading.Lock()
        self.results_lock = threading.Lock()
        self.statuses = {}
        self._say = say or print

    # -- output ------------------------------------------------------------------------
    def say(self, msg):
        with self.print_lock:
            self._say(msg)

    def tag(self, p, ws):
        return '[%s%s] ' % (p.dirname, ' @' + ws.name if self.parallel > 1 else '')

    # -- setup -------------------------------------------------------------------------
    def vivado(self):
        return Vivado(self.cfg.vivado, cwd=self.cfg.vivado_cwd, procs=self.procs)

    def cwd_for(self, ws, run_dir):
        """Where Vivado starts: [vivado] cwd, else the run directory (its .Xil/ and stray logs
        stay with the run) -- or, for Windows Vivado with the output on the Linux side, the
        workspace root."""
        if self.cfg.vivado_cwd:
            return self.cfg.vivado_cwd
        if not self.vivado().windows or on_windows_drive(run_dir):
            return run_dir
        return ws.root

    def done_record(self, p):
        path = self.out_dir / p.dirname / 'done.json'
        if not path.exists():
            return None
        try:
            with open(path, encoding='utf-8') as f:
                return json.load(f)
        except (OSError, ValueError):
            return None

    def write_meta(self):
        self.out_dir.mkdir(parents=True, exist_ok=True)
        if self.sweep_text and not (self.out_dir / 'sweep.vsw').exists():
            (self.out_dir / 'sweep.vsw').write_text(self.sweep_text, encoding='utf-8')
        (self.out_dir / 'plan.txt').write_text(self.plan_text + '\n', encoding='utf-8')
        shutil.copy2(self.cfg.path, self.out_dir / 'vsweep.toml')

    def make_workspaces(self):
        if self.parallel == 1:
            return [workspace.Workspace(self.cfg)]
        errors, warnings = workspace.check_clonable(self.cfg)
        for w in warnings:
            self.say('warning: ' + w)
        if errors:
            raise workspace.WorkspaceError('--parallel needs a project that can be copied:\n  ' + '\n  '.join(errors))
        size = workspace.size_of(self.cfg)
        self.say('copying the project %d times (%.1f GB each) into %s'
                 % (self.parallel, size / 1e9, self.cfg.root / '.vsweep' / 'ws'))
        out = []
        for i in range(self.parallel):
            if self.stopping.is_set():
                break
            out.append(workspace.clone(self.cfg, i))
        return out

    # -- the sweep ---------------------------------------------------------------------
    def run(self):
        self.write_meta()
        todo = []
        for p in self.planned:
            rec = self.done_record(p) if self.resume else None
            if rec and rec.get('status') == OK and rec.get('digest') == p.digest:
                self.say('[%s] done in an earlier run, skipped' % p.dirname)
                self.statuses[p.name] = 'skipped'
            else:
                todo.append(p)
        guard = Guard(self.cfg, self.out_dir)
        threads, workspaces = [], []
        catch = (signal.SIGTERM, signal.SIGHUP)
        old = {s: signal.getsignal(s) for s in (signal.SIGINT,) + catch}

        def on_signal(signum, frame):
            raise Interrupted(signal.Signals(signum).name)

        self.say('output: %s' % self.out_dir)
        try:
            for s in catch:
                signal.signal(s, on_signal)
            # Sequential builds edit the project's own .vh files; clones leave them alone.
            guard.acquire(self.cfg.vh if self.parallel == 1 else [])
            self.vivado().check_cwd(self.cwd_for(workspace.Workspace(self.cfg), self.out_dir))
            if todo:
                workspaces = self.make_workspaces()
                jobs = max(1, self.cfg.jobs // len(workspaces))
                if len(workspaces) > 1:
                    self.say('%d workers, %d jobs each' % (len(workspaces), jobs))
                q = queue.Queue()
                for p in todo:
                    q.put(p)
                threads = [threading.Thread(target=self.worker, args=(ws, q, jobs), daemon=True)
                           for ws in workspaces]
                for t in threads:
                    t.start()
                while any(t.is_alive() for t in threads):
                    for t in threads:
                        t.join(0.2)
        except (KeyboardInterrupt, Interrupted) as e:
            self.interrupted = True
            self.stopping.set()
            self.say('\ninterrupted (%s): stopping Vivado' % (e or 'Ctrl-C'))
            self.procs.kill_all()
            while any(t.is_alive() for t in threads):
                try:
                    for t in threads:
                        t.join(0.2)
                except (KeyboardInterrupt, Interrupted):
                    self.procs.kill_all()
        finally:
            for s in (signal.SIGINT, signal.SIGTERM, signal.SIGHUP):
                signal.signal(s, signal.SIG_IGN)       # nothing may interrupt the restore
            try:
                for path in guard.restore():
                    self.say('restored %s (byte-identical)' % path)
                guard.release()
                if not self.keep_workspaces and self.parallel > 1:
                    workspace.remove_all(self.cfg)      # also a copy half made when Ctrl-C came
                with self.results_lock:
                    write_results(self.out_dir)
            finally:
                for s, h in old.items():
                    signal.signal(s, h)
        records = load_records(self.out_dir)
        if records:
            self.say('\n' + summary_table(records))
            self.say('results: %s' % (self.out_dir / 'results.csv'))
        if self.interrupted:
            return 130
        failed = [n for n, s in self.statuses.items() if s not in (OK, 'skipped')]
        return 1 if failed else 0

    def worker(self, ws, q, jobs):
        vivado = self.vivado()
        while not self.stopping.is_set():
            try:
                p = q.get_nowait()
            except queue.Empty:
                return
            try:
                status = self.execute(p, ws, vivado, jobs)
            except Exception:
                status = 'error'
                tb = traceback.format_exc()
                self.say(self.tag(p, ws) + 'ERROR\n' + tb)
                try:
                    run_dir = self.out_dir / p.dirname
                    run_dir.mkdir(parents=True, exist_ok=True)
                    self.finish(p, ws, run_dir, self.base_record(p, ws), 'error', [tb.strip().splitlines()[-1]],
                                [], {}, time.time())
                except Exception:
                    pass
            self.statuses[p.name] = status
            if status != OK and self.stop_on_fail:
                self.stopping.set()

    def base_record(self, p, ws):
        return {
            'index': p.run.index, 'name': p.name, 'dirname': p.dirname, 'parent': p.run.parent,
            'overrides': {k: fmt(v) for k, v in p.run.overrides.items()},
            'settings': {k: fmt(v) for k, v in p.run.settings.items()},
            'state': {k: fmt(v) for k, v in p.state.items()},
            'changes': p.changes, 'reference': p.reference, 'delta': p.delta, 'digest': p.digest,
            'workspace': ws.name,
            'started': datetime.datetime.now().isoformat(timespec='seconds'),
        }

    def execute(self, p, ws, vivado, jobs):
        cfg = self.cfg
        run_dir = self.out_dir / p.dirname
        if run_dir.exists():
            shutil.rmtree(run_dir)
        (run_dir / 'vh').mkdir(parents=True)
        t0 = time.time()
        record = self.base_record(p, ws)
        with open(run_dir / 'settings.json', 'w', encoding='utf-8') as f:
            json.dump(record, f, indent=1)
        names = [Path(path).name for path in p.rendered]
        for i, (path, data) in enumerate(p.rendered.items()):
            name = Path(path).name if names.count(Path(path).name) == 1 else '%d_%s' % (i, Path(path).name)
            (run_dir / 'vh' / name).write_bytes(data)
        tag = self.tag(p, ws)
        self.say('[%d/%d] %s%s  %s' % (p.run.index, self.total, p.dirname,
                                       ' @' + ws.name if self.parallel > 1 else '',
                                       ', '.join(p.delta if p.reference not in (None, 'base') else p.changes)
                                       or '(no change)'))
        timeout = cfg.timeout_hours * 3600 or None
        context = {'RUN_NAME': p.name, 'RUN_INDEX': p.run.index, 'RUN_DIR': str(run_dir),
                   'WORKSPACE': str(ws.root), 'XPR': str(ws.xpr),
                   'SETTINGS_JSON': str(run_dir / 'settings.json'), 'BIT': '', 'LTX': '',
                   'VIVADO': cfg.vivado}
        problems, warnings, times = [], [], {}

        # 1. pre_build hook (before the .vh changes, so it sees the workspace as it is)
        if cfg.pre_build:
            hr = hooks.run('pre_build', cfg.pre_build, context, ws.root, str(run_dir), vivado, timeout)
            if not hr.ok:
                return self.finish(p, ws, run_dir, record, 'pre_build_failed', [hr.message], [], hr.metrics, t0)

        # 2. the .vh files, and the synthesis session they replace
        before = None
        old_vds = reports.find_vds(ws.synth_dir) if ws.synth_dir.is_dir() else None
        if old_vds:
            before = reports.parse_vds(reports.read_text(old_vds))['session']
        for path, data in p.rendered.items():
            ws.map(path).write_bytes(data)

        # 3. build and report, in one Vivado session
        (run_dir / 'build.tcl').write_text(build_tcl(cfg, ws, run_dir, vivado, jobs), encoding='utf-8', newline='\n')

        def on_marker(kind, text):
            if kind == 'STEP':
                self.say('    %s%s  (%s)' % (tag if self.parallel > 1 else '', text, duration(time.time() - t0)))
            elif kind == 'TIME':
                step, _, secs = text.partition(' ')
                times[step + '_s'] = secs
            elif kind == 'WARN':
                warnings.append(text)
        res = vivado.run(run_dir / 'build.tcl', run_dir / 'build.log', run_dir / 'vivado.log',
                         cwd=self.cwd_for(ws, run_dir), timeout=timeout, on_marker=on_marker)
        if res.ok:
            status = OK
        elif self.interrupted:
            status = 'interrupted'
            problems.append('stopped by the user')
        elif res.timed_out:
            status = 'timeout'
            problems.append('the build ran longer than timeout_hours = %g' % cfg.timeout_hours)
        else:
            status = 'build_failed'
            problems += res.texts('FAIL') or ['vivado exited %s before finishing; see build.log' % res.rc]

        # 4. is the netlist the one this run asked for?
        if status == OK:
            vds = reports.find_vds(run_dir)
            if vds:
                text = reports.read_text(vds)
                vp = verify.check_fresh(text, before) + verify.check_build(text, p.state, cfg.verify)
            else:
                vp = ['no synthesis log (.vds) came back from the run']
            if vp:
                status = 'verify_failed'
                problems += vp
        metrics = reports.collect(str(run_dir), cfg.hierarchical)
        metrics.update(hooks.merge_metrics(str(run_dir), {}))
        metrics.update(times)
        if status == OK:
            for h in cfg.hierarchical:
                if not any(k.startswith(h.strip('/') + '.') for k in metrics):
                    warnings.append('no instance %s in the hierarchical reports (flattened by synthesis? '
                                    'keep_hierarchy keeps it)' % h)

        # 5. post_build hook: only for a build that is what it claims to be
        if status == OK and cfg.post_build:
            bits = glob.glob(str(run_dir / '*.bit')) or glob.glob(str(ws.map(cfg.runs_dir) / cfg.impl_run / '*.bit'))
            ltxs = glob.glob(str(run_dir / '*.ltx')) or glob.glob(str(ws.map(cfg.runs_dir) / cfg.impl_run / '*.ltx'))
            context.update(BIT=bits[0] if bits else '', LTX=ltxs[0] if ltxs else '', STATUS=status)
            hr = hooks.run('post_build', cfg.post_build, context, ws.root, str(run_dir), vivado, timeout)
            metrics.update(hr.metrics)
            if not hr.ok:
                status = 'post_build_failed'
                problems.append(hr.message)
        return self.finish(p, ws, run_dir, record, status, problems, warnings, metrics, t0)

    def finish(self, p, ws, run_dir, record, status, problems, warnings, metrics, t0):
        record.update(status=status, problems=problems, warnings=warnings, metrics=metrics,
                      finished=datetime.datetime.now().isoformat(timespec='seconds'),
                      seconds=round(time.time() - t0, 1))
        tmp = run_dir / 'done.json.tmp'
        with open(tmp, 'w', encoding='utf-8') as f:
            json.dump(record, f, indent=1)
        os.replace(tmp, run_dir / 'done.json')
        with self.results_lock:
            write_results(self.out_dir)
        tag = self.tag(p, ws) if self.parallel > 1 else ''
        if status == OK:
            self.say('    %sok  %s  [%s]' % (tag, headline(metrics), duration(record['seconds'])))
        else:
            self.say('    %s%s: %s  [%s]' % (tag, status.upper(), '; '.join(problems), duration(record['seconds'])))
        for w in warnings:
            self.say('    %swarning: %s' % (tag, w))
        self.statuses[p.name] = status
        return status


